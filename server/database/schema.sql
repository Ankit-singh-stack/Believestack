UPDATE projects p
SET category_id = legacy.category_id
FROM (
  SELECT DISTINCT ON (project_id) project_id, category_id
  FROM project_category_links
  ORDER BY project_id, category_id
) AS legacy
WHERE p.id = legacy.project_id AND p.category_id IS NULL;

UPDATE projects p
SET features = legacy.features
FROM (
  SELECT project_id, jsonb_agg(feature ORDER BY feature) AS features
  FROM project_feature_links
  GROUP BY project_id
) AS legacy
WHERE p.id = legacy.project_id AND p.features = '[]'::jsonb;

UPDATE services s
SET features = legacy.features
FROM (
  SELECT service_id, jsonb_agg(feature ORDER BY feature) AS features
  FROM service_features
  GROUP BY service_id
) AS legacy
WHERE s.id = legacy.service_id AND s.features = '[]'::jsonb;

